//------------------------------------------------------------------------------------------------------------------
// ① 滤波参数
//------------------------------------------------------------------------------------------------------------------
// 采样分两层，顺序是"内层先、外层后"：
//   内层 adc_mean_filter_convert(ch, ADC_MEAN_COUNT) —— 库自带的连续采样求平均，负责压掉单次采样里的
//        高频噪声（MOS 开关噪声、ADC 量化抖动）；
//   外层 去极值平均（get_data.c 里的 median_average_filter）—— 对 FILTER_N 个内层结果再去掉一个最大值
//        和一个最小值后求平均，专门对付尖峰干扰（比如电机换向瞬间窜进来的那一针）。
// 代价要先算清楚：每个电感每周期要转换 FILTER_N * ADC_MEAN_COUNT 次，4 路合计 4*FILTER_N*ADC_MEAN_COUNT 次。
// adc_convert 是"发起转换 + 死等完成"的阻塞实现（见 zf_driver_adc.c），单次大约 1~2us，
// 用默认的 6*3=18 次/路、4 路共 72 次，大约 0.1ms，只占 10ms 周期的 1%，完全吃得下。
// 如果以后把 main.c 里的中断周期压到 1ms 以内，记得把下面两个数一起往下调，否则会挤爆中断。
#define ADC_MEAN_COUNT              (3)         // 内层库均值滤波深度，至少 1
#define FILTER_N                    (6)         // 外层去极值平均的点数，至少 3 才有"极值"可去

//------------------------------------------------------------------------------------------------------------------
// ② 归一化参数
//------------------------------------------------------------------------------------------------------------------
// 归一化做的事情：把"这个电感现在读到多少"翻译成"这个电感现在有多强"，统一到 0~100。
// 为什么非做不可：不做归一化的话，电池从 8.4V 掉到 7.0V、车高变化、运放温漂，都会让所有电感读数整体变小，
// 于是差比和出来的偏差跟着漂，直道上会莫名其妙往一边偏。
// 标定方法：车放赛道上，让某个电感尽量达到"最强"（通常是探头正对导线），记下读数当 max；
//          再把车抬离赛道（或完全离开导线）记下读数当 min。下面给的是保守占位值，上车必须重新标。
// 注意 adc_min 必须严格小于 adc_max，否则归一化会除零；代码里已经做了保护（结果记 0），
// 所以如果屏幕上 4 路归一化值全是 0，第一件事就是检查标定值是不是没设对。
#define ADC_NORM_MIN_DEFAULT        (0)         // 电感归一化下限默认值
#define ADC_NORM_MAX_DEFAULT        (3800)      // 电感归一化上限默认值
#define ADC_NORM_MAX_VALUE          (100)       // 归一化满量程（0~100，别改，改成别的下游都要跟着改）

//------------------------------------------------------------------------------------------------------------------
// ③ 差比和参数
//------------------------------------------------------------------------------------------------------------------
// 公式：误差 = (左和 - 右和) / (左和 + 右和) * DIFF_SUM_SCALE
// 为什么从"直接相减"换成"差比和"：直接相减的结果会随信号整体强弱一起缩放，而差比和是"差 / 和"，
// 分母自带归一化，信号整体变强变弱时这个比值基本不变，所以直道更稳、弯道响应更线性。
//
// ★ DIFF_SUM_SCALE 和舵机的 kp 是"配对"的，绝对不能只改一个：
//   原来的方案是 raw 直接相减，量程 ±4095。理论上 raw 差 ≈ 4095 × 偏差比例 d；
//   而差比和（左和右和都归一化之后）恰好 ≈ d，量程 ±1。
//   所以把 DIFF_SUM_SCALE 取成 4000，就能让新误差的量程（±4000）和原来的（±4095）对齐，
//   斜率也对齐，于是 kp = 0.008 这个整定值可以原封不动继续用，最大打角依然在 ±15° 限幅附近收住。
//   如果哪天你调了这个倍数，请按 kp_new = kp_old * 4000 / DIFF_SUM_SCALE 反过来补一下 kp。
#define DIFF_SUM_SCALE              (4000.0f)   // 差比和放大倍数，量程 ±4000
#define LINE_LOST_THRESHOLD         (30)        // 左右归一化值之和低于此值判定丢线（取值范围 0~400）
#define LINE_LOST_MOTOR             (10)        // 丢线停车阈值：左右归一化之和低于此值才停电机（比舵机丢线阈值更严，避免信号一弱就刹死）

//------------------------------------------------------------------------------------------------------------------
// ④ 弯道速度规划参数（直道提速 + 弯道降速 + 入弯提前减速 + 出弯提速）
//------------------------------------------------------------------------------------------------------------------
// 目标：让车在直道上跑满速，在弯道里降到一个"能安全通过"的速度，出弯后再加速回满速。
// 这样整圈的平均速度反而更高——用弯道的"慢"换直道的"快"。
//
// 三个子功能：
//   1) 连续降速：目标速度随 |adc_error|（差比和偏差绝对值，越大 = 弯越急）**非线性**下降，但有地板。
//      公式：speed_target = MAX - (MAX - MIN) * (|e| / E_FULL)^K
//        |e| = 0         -> 满速 MAX
//        |e| >= E_FULL   -> 地板 MIN
//        中间那段过渡曲线的形状全由指数 K 决定：
//          K = 1   完全退化成原来的线性直线（E_FULL 是按 GAIN 反算的，所以数值和改动之前逐点相等）
//          K > 1   凸曲线：小偏差时几乎不减速，大偏差时降得很陡
//                  -> 缓弯保持高速、急弯该降才降；整体更激进，平均速度更高
//          K < 1   凹曲线：偏差一出来就明显减速，越往后越平缓
//                  -> 更早更保守，适合抓地不够、或者怕进弯太快甩出去
//      ★ 为什么比线性更合理：电感偏差和"弯有多急"本来就不是线性关系。
//        小偏差大多来自直道抖动或很缓的弯，线性公式在这种地方白白扣掉一大截速度；
//        而真正急弯的偏差会迅速冲到很大，这时候需要的是果断、快速地把速度压下去。
//        指数曲线能把"缓弯别掉速"和"急弯降得狠"这两头同时照顾到。
//   2) 入弯提前减速：看 |adc_error| 的变化率（导数）。入弯前偏差会开始快速增大，
//      变化率超过阈值就"提前"把速度压到入弯速度，而不是等偏差已经大了才减。
//      这是在"四个电感一排、没有前瞻"的限制下，唯一能做提前减速的手段。
//   3) 出弯提速：|adc_error| 回落到接近 0（回到直道）就恢复满速。
//
// ★ 单位说明：速度单位是"脉冲/周期"（编码器增量），不是 m/s，所以下面这些数值都是脉冲数，
//   必须用开环实测的屏幕 SPD 读数来标定，不能凭感觉填。
#define SPEED_CURVE_MAX             (900.0f)   // 直道满速（脉冲/周期）。用户指定目标 1300，尚未实测，上车按屏幕 SPD 标定
#define SPEED_CURVE_MIN             (520.0f)    // 弯道最低速度（地板）。再急的弯也不会低于这个值，避免越弯越慢、慢到离谱
#define SPEED_CURVE_GAIN            (0.29f)     // 弯道降速系数。★ 换成指数曲线之后它不再是"斜率"，
                                                //   而是用来反算偏差满量程：E_FULL =（MAX-MIN）/ GAIN ≈ 1310。
                                                //   也就是 |e| 涨到约 1310 就压到地板速度。
                                                //   调大 = 更早降到地板（整体更慢、更保守）
                                                //   调小 = 更晚到底（直道/缓弯更敢跑）
#define SPEED_CURVE_EXP_K           (1.0f)      // ★ 降速曲线的指数 K。
                                                //   K = 1.0 -> 和最早的线性曲线逐点相等（当前取值，实测过的稳妥状态）
                                                //   K > 1   -> 更激进：缓弯几乎不掉速，急弯陡降
                                                //   K < 1   -> 更保守：偏差一出来就开始减速
                                                //
                                                // ★★ 实测记录（重要，别再往反方向试）：
                                                //   把 K 设成 1.5 之后，**普通弯道进弯变迟、车往外飘**。
                                                //   原因：K>1 在中度偏差区（|e| 300~800）比线性快 45~55 脉冲，
                                                //   而这台车只有四个电感、没有前瞻，进弯本来就晚，
                                                //   再快一点就直接变成"拐不动、推头出去"。
                                                //   也就是说：这台车需要的是**更早减速**，方向应该往 K < 1 走，
                                                //   而不是往 K > 1。想试就从 0.8 开始，别再往上加。
#define SPEED_CURVE_E_FULL          ((SPEED_CURVE_MAX - SPEED_CURVE_MIN) / SPEED_CURVE_GAIN)
                                                // 偏差满量程：|e| 到这里就压到地板速度。
                                                // 用 GAIN 反算而不是直接写死，是为了保证 K=1 时
                                                // 和原来的线性公式完全等价（方便 A/B）
#define SPEED_CURVE_ENTER_RATE      (100.0f)    // 入弯提前减速阈值（偏差变化率，脉冲/周期）。
                                                // 当 |adc_error| 相比上一拍增大超过此值时，判定"正在入弯"，提前把速度压到 SPEED_CURVE_ENTER_SPEED。
                                                // 调小 = 更早触发提前减速（但直道轻微抖动也可能误触发）；调大 = 更晚触发（减速不够提前）。
#define SPEED_CURVE_ENTER_SPEED     (400.0f)    // 入弯提前减速的目标速度（脉冲/周期）。略高于弯道地板，作为"进入弯道"的过渡速度。
                                                // 提前降到这个速度后，再交给连续降速逻辑继续往下压到地板。
#define SPEED_CURVE_EXIT_ERROR      (330.0f)    // 出弯判断阈值：|adc_error| 低于此值判定"已回到直道"，恢复满速。
                                                // 调小 = 出弯提速更谨慎（等偏差更小才提速）；调大 = 更激进（出弯更早提速，可能还没出完就提速）。
#define SPEED_CURVE_SMOOTH          (0.20f)     // 目标速度的一阶低通平滑系数（0~1）。
                                                // 速度目标如果每拍跳变（比如丢线→恢复、直道→弯道），会通过 PI 造成油门突变。
                                                // 用一阶低通让 speed_target 平滑过渡：新目标 = 旧目标*(1-k) + 期望目标*k。
                                                // k 越小越平滑（但响应越慢）；k=1 等于不平滑。0.20 是"较平滑但响应可接受"的折中。

//------------------------------------------------------------------------------------------------------------------
// ⑤ 舵机打角参数（P 比例 + D 微分）
//------------------------------------------------------------------------------------------------------------------
// 原来是纯 P（proportion）：打角 = 中值 - kp * 偏差。问题：纯 P 只对"当前偏差"反应，
// 弯道里偏差变化快，舵机打角会"滞后"，容易冲出赛道。
// 加 D（derivative，微分）：对"偏差的变化率"反应，相当于提前预判——偏差还在增大时，就提前多打一点角，
// 让打角更"跟手"，弯道里更稳，也能允许更快的过弯速度（这就是"弯道提速"在打角侧的保障）。
#define SERVO_KD                    (0.0016f)   // 舵机微分系数。打角 = 中值 - kp*偏差 - kd*(偏差 - 上次偏差)。
                                                // 偏差量程 ±4000，10ms 一拍偏差变化通常几十~几百，所以 kd 要取很小（kp 的约 1/10）。
                                                // 调大 = 打角对"弯道变化"更敏感、更跟手，但过大抖动会放大噪声、车会抖舵。
                                                // 调小 = 更接近纯 P。0 等于关掉微分。

//------------------------------------------------------------------------------------------------------------------
// ⑥ 速度环参数
//------------------------------------------------------------------------------------------------------------------
// 编码器测速原理：get_encoder() 每周期"先把计数读走、再立即清零"，所以读到的是"本采样周期内的脉冲增量"，
// 正比于轮速。单位是"脉冲 / 周期"，不是 m/s。
//
// ★ 本车实测接线（标定日期记录在这里，以后改线一定要同步改这一段）：
//     左轮编码器 -> 编码器接口 4，对应本工程的 ENCODER_4（库里的 QTIMER2_ENCODER2）
//     右轮编码器 -> 编码器接口 3，对应本工程的 ENCODER_3（库里的 QTIMER2_ENCODER1）
//   车上只装了这两路。bit0~bit3 依次对应 ENCODER_1~4，所以掩码只允许 bit2 和 bit3 参与测速：
//   另外两路没接线、引脚悬空，而正交解码器会把悬空引脚上的噪声边沿也当脉冲数，留在掩码里
//   会直接把平均速度污染掉（表现出来就是速度乱跳或者数值离谱）。
#define SPEED_ENCODER_MASK          (0x0C)      // bit2 = ENCODER_3(右轮)，bit3 = ENCODER_4(左轮)

// 每路编码器的"前进方向"符号：手推车向前走时，若这一路读数为负，就把对应宏改成 -1 把它翻正。
// 实测：左轮(ENCODER_4)向前转读数是负的 -> 取 -1；右轮(ENCODER_3)向前转读数是正的 -> 保持 +1。
//
// ★★ 这一项配错的后果极其严重，必须理解清楚：
//    速度环是"偏差 = 目标 - 实测"的负反馈，它成立的前提是"占空比变大 -> 实测速度变大(正数)"。
//    一旦反馈是负的，负反馈就变成正反馈：转得越快 -> 读数越负 -> 偏差越大 -> 占空比越大 -> 转得更快。
//    增量式 PI 在这种情况下一个周期就能把输出推到 MAX_PWM_DUTY，所以现象就是"一通电电机就飞快"。
//    以后一旦再看到这种现象，第一个要查的就是这里（以及编码器 A/B 两相有没有接反）。
#define ENCODER_DIR_1               (+1)        // 未接线，留作以后扩展
#define ENCODER_DIR_2               (+1)        // 未接线，留作以后扩展
#define ENCODER_DIR_3               (+1)        // 右轮：向前转读数为正
#define ENCODER_DIR_4               (-1)        // 左轮：向前转读数为负，所以翻正

// ★ 速度环总开关：0 = 开环（占空比固定为 SPEED_START_DUTY，行为跟改造前的原例程一样），1 = 闭环 PI。
//   第一次上车、或者怀疑编码器接线又被动过时，先保持 0。开环下车只会按 SPEED_START_DUTY 慢速转，
//   可以放心地看屏幕上的 SPD，确认"手推车向前时速度是正数、数值合理"。确认之后再改成 1。
#define SPEED_LOOP_ENABLE           (1)

#define SPEED_TARGET_DEFAULT        (900.0f)    // 目标速度（脉冲/周期）
                                                // ★ 这仍是占位值，必须实测标定：开环状态下读屏幕上的
                                                //   SPD，取你真正想要的那个读数填进来。
                                                //   注意别填得比"实际能跑到的速度"还小——那样闭环会一路
                                                //   把占空比压到 0，车反而不走。
                                                //   注意：速度环的目标值现在由"弯道速度规划"动态计算（见 ④ 段），
                                                //   这里的 SPEED_TARGET_DEFAULT 只是 speed_target 的初始值/兜底值。
                                                //   建议和 SPEED_CURVE_MAX（直道满速）保持一致。
#define SPEED_START_DUTY            (30.0f)     // 开环占空比 / 闭环起始占空比
#define SPEED_PI_KP                 (0.30f)     // 速度环比例系数（增量式）
#define SPEED_PI_KI                 (0.7f)     // 速度环积分系数（增量式）

// 单周期偏差限幅：一个坏采样（电机换向尖峰、偶发丢脉冲）最多让输出动这么多，不可能一步打满。
// 取值建议：比"50% 占空比时屏幕上的 SPD 读数"大 2~3 倍就够。
#define SPEED_ERROR_LIMIT           (500.0f)
// 单周期占空比变化上限（百分点/周期）。10ms 一个周期，取 3.0 相当于约 150ms 从 0 加到 50%，
// 既当软启动用，也能挡住"一个坏采样就把车弹出去"。
#define SPEED_DUTY_SLEW             (3.0f)
// 反馈符号故障自检（第一道）：占空比已经给到 20% 以上（确实在驱动电机），平均速度却连续 30 个周期
// 都低于 -100，说明反馈符号依然是反的，此刻再给油就是正反馈失控 -> 立刻把占空比压到 0 并锁住，
// 屏幕 F 显示 1。宁可车停下来让你查线，也不要它满速冲出去。
