// ★ 阈值不要贴着"实际可能出现的数值"取：一开始取的是 -200，但满占空比、符号又反的情况下反馈恰好就是
//   -200，严格的 < 判断会一直不成立，自检形同虚设——这个坑是仿真测出来的，不是想出来的。
#define SPEED_FAULT_DUTY_MIN        (20.0f)
