//------------------------------------------------------------------------------------------------------------------
// ⑦ 环岛参数（外侧先饱和 -> 内侧隆起 -> 内侧落回个位数，三级识别 + 三段式打角）
//------------------------------------------------------------------------------------------------------------------
// 实测现象（只处理"向左进环岛"）。这里记的是真车上一路看下来的数，不是估的：
//   ① 车还没到岔口：最外侧那一路 n[0] 被岔路那根线顶起来，从直道的 70 一路涨到 100；
//   ② 接着内侧那一路 n[1] 从个位数开始涨，最高到 40 左右；
//   ③ 然后 n[1] 又落回个位数 —— 这一刻车身正好在"环岛与直道的交界处"。
//
// 所以识别根本不用去猜"什么时候到岔口"：那一路"先隆起、再回落"的包络本身就带着时钟。
//   候选（IDLE->WAIT）  ：外侧 >= RB_OUTER_TH，且比内侧高出 RB_OUTER_GAP（先外后内）
//   确认（WAIT->HUMP）  ：某一路涨过 RB_INNER_TH、且涨幅够 RB_INNER_RISE，说明它真鼓起来了
//   到岔口（HUMP->ENTER）：那一路跌到"峰值 × RB_FALL_RATIO" = 车头压到交界处，这时候才该打角
//
// 为什么"涨起来又回落"这一条最值钱：
//   直道上内侧大约 70，普通弯道上那一侧只会一直高、不会掉回去；
//   只有岔口把导线甩到阵列外侧，才会出现"先鼓一个包再回落"的形状。
//   所以它既能定位交界处，又顺手帮我们把急弯排除掉了 —— 比拿总强度去猜靠谱得多。
//   ★ 注意：驼峰到底出现在哪一路是程序自己找的（n[1]~n[3] 里涨得最猛的那路），
//     不是写死的 n[1] —— 实测这台车一直是 n[2]，写死就永远识别不到。
//
// ★ 换车、换探头高度之后要重标的只有三个数：RB_OUTER_TH / RB_INNER_TH / RB_INNER_RISE。
//   车放直道上先看 N0~N3 记下平时的值，再慢慢把车推近环岛：
//   外侧最高到多少 -> RB_OUTER_TH 取比它低一点；驼峰鼓多高 -> RB_INNER_TH 取它的一半；
//   从起点涨多少   -> RB_INNER_RISE 取实测涨幅的一半左右（屏幕第 0 行会直接显示涨幅和峰值）。
//   触发时机不用重标，它是按峰值比例算的，会自动跟着峰值走。
//------------------------------------------------------------------------------------------------------------------
#define RB_ENABLE                   (1)         // 环岛总开关：0 = 完全不管环岛，行为和加这一段之前一样
#define RB_OUTER_TH                 (95)        // ① 外侧"已经饱和"：直道约 70，岔口能顶到 100
#define RB_OUTER_GAP                (10)        // ① 近侧外沿要比同侧内沿高出这么多，才算"外侧先站起来"
#define RB_OUTER_ASYM               (15)        // ①★ 单侧性：近侧外沿 n[0] 要比**对侧外沿 n[3]** 高出这么多。
                                                //    这一条专治十字路口：十字路口那根线横穿赛道，左右同时被顶起，
                                                //    n[0] ≈ n[3]、差值接近 0，会被挡掉；环岛的岔口线只在一侧，
                                                //    差值通常很大，照常通过。
                                                //    ★ 如果加了这条之后**环岛不识别了**，说明你的环岛入口处
                                                //    两侧也被同时顶高，把这个值调小（10 -> 5），
                                                //    实在不行设 0 就等于关掉这条判据（回到只在十字路口会误判的状态）。
                                                //    屏幕上 N0~N3 随时能看到，n[0]-n[3] 就是这个值的实测依据
#define RB_OUTER_WEAK               (70)        // 确认窗口里外侧掉到这个值以下、并且连续掉够下面那个拍数，
                                                // 才判"刚才那是假警报"。岔路那根线扫过去时外侧掉一两拍是正常的，
                                                // 掉一拍就撤退会把整次识别腰斩在驼峰中间
#define RB_OUTER_WEAK_TICKS         (10)        // 外侧去抖：连续这么多拍低于 RB_OUTER_WEAK 才算真的没了
#define RB_INNER_TH                 (20)        // ② 驼峰峰值的下限。实测鼓到 40 左右，取一半最稳
#define RB_INNER_RISE               (6)         // ② 驼峰必须"从起点涨够这么多"，才算真的鼓起来了。
                                                //    这一条把"本来就待在高位"的普通弯道排除掉：
                                                //    弯道上内侧起点就高，涨不出这个差值。
                                                //    ★ 这个数是被实测逼下来的：有一次识别成功时窗口里显示
                                                //    "涨幅 11"，而当时阈值是 15（后来放到 10）—— 只差 1 就过不了，
                                                //    这就是"有时候完全没反应"的另一半原因（驼峰是真的，但卡在门槛边上）。
                                                //    现在取 6，留出 5 的余量。再往下调就要小心弯道误判了。
                                                //    屏幕上 P 那组的中间那个数就是实际涨幅，对着它调

//---- ③ 什么时刻开始打角（这个数直接决定"进环岛早还是晚"）----
// 原来是"驼峰落回固定值 12 以下"，结果是等它几乎跌到底才动，车已经压过交界处了。
// 现在改成按**峰值的比例**触发：跌到峰值 × RB_FALL_RATIO 就打角。
//   好处是不受峰值大小影响：峰值 23 和峰值 44 用的是同一个"相对位置"，
//   不会出现"峰值大的那次触发得很早、峰值小的那次触发得很晚"。
// 调法：嫌晚就调大，嫌早/打角过头就调小。
//   峰值 40 时：0.34 -> 落到 13.6 就打角；0.30 -> 落到 12；0.38 -> 落到 15。
// ★ 标定记录（同一台车、同一个环岛，一路夹逼下来的）：
//     固定阈值 12（峰值 44 时等效 0.27）-> 太晚，车已压过交界处；
//     峰值 x 0.50 / 0.38                 -> 太早，还没到环岛就转了；
//     峰值 x 0.30                        -> 稍微有一点点晚（就差一点点）；
//   现在取 0.34。比例这一格大约对应十几拍的差别，再细就靠下面的延时。
//   ★ 两个旋钮的分工：比例负责"粗定位"，延时负责"往后微调"。
//     也就是说延时只能把时机往后推；想提前只能调大比例。
//     所以最佳用法是：先把比例放到"稍微偏早"的位置，再用延时一格一格往后顶到刚好。
#define RB_FALL_RATIO               (0.325f)     // 触发点 = 峰值 × 这个比例

//---- ③b 回落之后再等几拍才打角（**精调时机用这个**）----
// 比例那个旋钮只能把触发点定在"下落的某个位置"，而下落那一段总共可能就十几拍，
// 一格比例对应的时间很短、也不好估计。这个延时是纯粹的 10ms 计数：
//   0  = 一跌到触发线就打角；
//   20 = 再往后推 200ms 才打角（车往前多走一段）。
// 用法：先把比例定在 0.30 让触发落到"下落完成"附近，再拿这个延时往前顶到你想要的时刻。
// 调法：还早 -> 加（20、30、40…）；晚了 -> 减回 0。
#define RB_ENTER_DELAY_TICKS        (0)
//---- 两个等待窗口 ----
// ★ 这两个数原来是 40(400ms) / 150(1.5s)，实测偏紧：车压低速度接近环岛时，内侧那个驼峰
//   可能要走上 1 秒多才起来，等不到就直接超时撤退，于是"交界处没人管舵机"，车被岔口的线拽出赛道。
//   现在放宽到 3s / 2s。放宽之所以安全，是因为 WAIT/HUMP 这两个阶段已经封住了"往右打舵"
//   （见 roundabout_forbid_right），多等一会儿车也只是直着走，不会跑到不该去的地方。
//   屏幕上 X 那一位会告诉你到底是不是卡在超时上：X=1 是 WAIT 超时，X=3 是 HUMP 超时。
#define RB_WAIT_TICKS               (300)       // 等驼峰鼓起来的窗口，单位 10ms；300 = 3s
#define RB_HUMP_TICKS               (200)       // 驼峰从鼓起到落回去最多给 2s，超了就丢掉这次机会

//---- ②★ 识别耗时上限（挡十字路口用）----
// 从"外侧饱和"这一拍算起，到决定打角为止的总拍数（WAIT + HUMP）。
// 实测两组数（同一台车、同一圈）：
//     十字路口误触发：46 拍（460ms），驼峰落在下标 3，峰值 47
//     真实环岛：      18 拍（180ms），驼峰落在下标 1，峰值 25
// 差了 2.5 倍，而且方向是"十字路口更慢更宽"。所以给一个上限：
// 超过这个拍数就放弃识别 —— 环岛 18 拍有接近 2 倍的余量，十字路口 46 拍会被砍掉。
// 调法：如果真实环岛也识别不到了（屏幕上 X 变成 5），把它加大（35 -> 50）。
//       如果十字路口还能混过去（X 没变成 5，RB 照样走到 3），把它减小（35 -> 28）。
#define RB_DETECT_MAX_TICKS         (35)        // 识别耗时上限，单位 10ms；35 = 350ms

//---- 三段式打角：单位是"度"，正数 = 往左打 ----
// ★★ 舵机方向是实测出来的，和直觉相反，务必看清：
//      中值 90；角度变大（→105）= 前轮往左；角度变小（→75）= 前轮往右。
//    依据：把 RB_STEER_TEST_DEG 设成 76 通电，前轮实际往右。
//    所以 RB_DELTA_ENTER 取 15 度，最后输出的是舵机角 105，贴着 SERVO_MOTOR_R_MAX(105)。
//    之前一直按"角度变小 = 往左"来写，三段打角整个是反的 —— 车在环岛处往右冲就是这个原因，
//    那几轮把 12/14/15 调来调去的数据全部作废。
//    想打得更狠，得把 SERVO_MOTOR_R_MAX 往上放宽（注意别顶到舵机真实行程）。
#define RB_DELTA_ENTER              (14.0f)     // 进入段：纯固定角，先把车头拽进圆弧。
                                                // 12 实测偏小（车拐进去不够狠），加到 14；上限是 15
// 绕行段：**独立的 PD + 一个固定左偏置**（不再是固定角，也不是主循迹那套增益）
//   为什么环岛里面要循迹：环岛内部导线就是一个圆，差比和跟直道、跟普通弯道没有任何区别，
//   完全可以正常跟线。之前一直用固定角，等于把循迹能力扔了，半径稍有出入就会一点点漂出去。
//   为什么还要加偏置：圆环上偏差大部分时间接近 0，纯 PD 会直着走。加一个恒定的左偏置，
//   等于告诉车"宁可往圆里多拐一点"，它自己就会贴着圆弧走；偏出去时 PD 会把它拉回来。
//
// ★★ 为什么 kp / kd 要单独一套（RB_KP / RB_KD），不直接用主循迹的 kp / kd：
//   主循迹的 kp 是"直道 + 普通弯道"整定出来的，环岛里导线曲率很大、而且还有固定偏置叠加，
//   两者最优增益本来就不是一个数。共用一套的后果是：你为了直道调 kp，环岛的手感跟着变，
//   改完环岛又要回头验直道 —— 来回互相牵制，永远调不干净。
//   分开之后，两个场景各调各的，互不干扰。
//   数学上二者是同一个形式：主循迹 angle = 90 - kp*偏差 - kd*变化率
//                          环岛   angle = 90 - RB_KP*偏差 - RB_KD*变化率 + RB_LOOP_BIAS
#define RB_KP                       (0.0055f)   // 环岛段专用的舵机比例系数。
                                                // 默认抄自主循迹的 0.0055，之后可以单独动：
                                                //   绕行时车身贴着导线左右小幅摆动 -> 减小
                                                //   偏离导线后回正太懒、贴着弯外侧走 -> 加大
#define RB_KD                       (0.0f)      // 环岛段专用的舵机微分系数。
                                                // ★ 默认 0：原来绕行段根本没有微分项，给 0 是为了
                                                //   **不改动现在已经调好的表现**。
                                                //   如果想要一点"提前量"抑制摆动，从 0.001 开始慢慢加，
                                                //   加过头会让车身发抖（这一项放大的是偏差的变化率）
#define RB_LOOP_BIAS                (8.0f)      // 绕行段的左偏置（度）。
                                                // 往弯里切太狠、蹭到内侧岛 -> 减小（7、6）
                                                // 往弯外飘 -> 加大（11、12），上限约 15（R_MAX 的行程）
#define RB_DELTA_EXIT               (3.0f)      // 出环段：相对中值的偏置（度）。正数 = 还带着一点左打。
                                                // 原来是 0（完全回正），实测出环之后车会往右蹭出赛道，
                                                // 说明"一刀切回正"太早了——出口那一段其实还需要一点左的余量。
                                                // 先给 3。还往右蹭就加到 5、6；如果变成往左甩过头，再减回 0 或取负。

//---- 识别阶段要不要"禁止往右打舵"（现在默认关掉）----
//   这个钳位原本是为了压住"车在交界处被猛地拽向右冲出赛道"。后来查明那个现象的真实原因是
//   舵机方向写反了（已经修好），所以它现在已经没有必要，而且**有副作用**：
//   它会在 WAIT / HUMP 这两个"还没确认"的阶段里，硬把舵机限制成"不许往右"。
//   一旦在别的地方（比如出环之后紧跟着的那条小弯）误判出一个候选，车进入 WAIT 之后
//   就在那条弯里转不了右，表现出来正是"某条弯突然走不稳"。
//   所以默认关闭。如果以后真的又出现"交界处往右冲"，再把它打开对比。
#define RB_FORBID_RIGHT_ENABLE      (0)

//---- 转向测试模式（标定用，平时必须是 0）----
// 设成非 0 的时候，set_servo_pwm() 会**忽略一切控制逻辑**，把舵机死死钉在这个角度输出。
// 用途：把车放地上让它自己跑，量"这台车给定某个舵角时，实际能跑出多大的圆"，一次就能分清
//   "是代码时机不对" 还是 "这台车根本转不了这么小的弯"。
//   测法（方向已经用这个办法确认过了）：RB_STEER_TEST_DEG 设 76，前轮往右；
//         设 104，前轮往左；设 90，车轮走直线。
//         想量最小转弯半径就把车放地上跑一圈，用粉笔标轨迹、量半径。
//   如果往左打满（105）跑出来的半径仍然大于环岛半径，那再怎么调 RB_LOOP_BIAS 都没用，
//   必须放宽 SERVO_MOTOR_R_MAX（先确认舵机真实行程，别顶死扫齿）。
#define RB_STEER_TEST_DEG           (0)

//---- 各段保持时长：单位是 10ms 周期，1 = 10ms ----
// ★★ 这一组是**按时间**算的，不是按距离。所以改 RB_SPEED_LIMIT 的时候，
//    同样的拍数车会走得更远 —— 绕行段会绕过头、出环点会往后挪。
//    换算：新的拍数 = 旧的拍数 × (旧速度 / 新速度)。
//    例：速度 470 -> 600，绕行 300 拍就要变成 300 × 470/600 ≈ 235 拍。
//    （进入时机的触发是看电感包络的，属于位置判据，不受速度影响，不用跟着改。）
#define RB_TICKS_ENTER              (20)        // 进入段时长，20 = 200ms
#define RB_TICKS_LOOP               (240)       // 绕行段时长。速度从 470 提到 600 后，按上面的换算
                                                // 从 300 收到 240，保证绕的弧长基本不变。
                                                // 如果仍然绕过头（出环点偏后）就继续减；绕不够就加
#define RB_TICKS_EXIT               (20)        // 出环段时长，20 = 200ms
#define RB_TICKS_COOL               (100)       // 冷却段时长，1000ms。出口会把同一个环岛再认一遍，
                                                // 而且**出环之后紧跟着的那条小弯也很容易满足入口特征**，
                                                // 冷却不够就会在小弯上误触发一次，车突然进 WAIT/ENTER、
                                                // 打角被接管 —— 那看起来就是"小弯走不稳"。
                                                // 原来 60（600ms）偏短，加长到 100
#define RB_TICKS_MAX                (1500)      // 单段安全阀，15s 还没走完就放弃，交回正常循迹

#define RB_SPEED_LIMIT              (470.0f)    // 环岛期间的速度硬上限（脉冲/周期）。允许低于 SPEED_CURVE_MIN。
                                                // 470 -> 600，注意 RB_TICKS_LOOP 已经按比例跟着收了（见上）。
