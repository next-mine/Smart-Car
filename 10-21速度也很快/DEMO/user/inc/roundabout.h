#ifndef _roundabout_h
#define _roundabout_h

#include "zf_common_headfile.h"
#include "my_common.h"

//------------------------------------------------------------------------------------------------------------------
// 环岛处理阶段（屏幕最上面那行的 RB 就是它，0~6 一一对应下面的枚举）
//
// 前半段（IDENTIFY）在回答"是不是环岛、什么时候到岔口"，判据全部来自实测的电感包络：
//   外侧先饱和（WAIT）→ 内侧隆起来确认不是急弯（HUMP）→ 内侧落回个位数 = 车到交界处（转 ENTER）。
// 后半段（ACT）在回答"怎么拐过去"：
//   为什么要拆成 ENTER / LOOP / EXIT 三段，而不是一个"环岛中"标志：
//   四个电感排成一排、没有前瞻，进了圆环之后"差比和"给出的偏差已经不完全是
//   "车头歪了多少"，它还混着圆圈本身带来的不对称；这时候最有用的不是闭环，
//   而是"先把车头拽进圆弧（ENTER）→ 按圆弧固定打角走一段（LOOP）→ 再回正出环（EXIT）"
//   这种分段的、可预测的动作。每一段都能单独调角度和时长，上车才好一个一个试。
//------------------------------------------------------------------------------------------------------------------
typedef enum
{
    RB_STATE_IDLE   = 0,            // 正常循迹，什么都没发生
    RB_STATE_WAIT   = 1,            // 外侧电感已经饱和，正在等内侧"隆起来"（证明这是岔口不是急弯）
    RB_STATE_HUMP   = 2,            // 内侧正在隆起（实测最高约 40），等它落回个位数
    RB_STATE_ENTER  = 3,            // 内侧落回个位数 = 车到交界处，强制打角拽进圆弧
    RB_STATE_LOOP   = 4,            // 绕行，保持往环岛内侧的打角
    RB_STATE_EXIT   = 5,            // 出环，把方向回正，让车顺着切线走出去
    RB_STATE_COOL   = 6,            // 冷却，这段时间不识别，防止在出口把同一个环岛再认一遍
    RB_STATE_MAX
} roundabout_state_enum;

//------------------------------------------------------------------------------------------------------------------
// 上一次识别"放弃"的原因（屏幕 X 那一位）。留着它是为了事后能复盘：
// 车没进环岛到底是"没看出来"还是"看出来了又撤了"，屏幕上一眼就能区分。
//------------------------------------------------------------------------------------------------------------------
#define RB_REASON_NONE              (0)     // 没放弃过，或者上一轮是正常走完的
#define RB_REASON_WAIT_TIMEOUT      (1)     // 卡在 WAIT：内侧一直没隆起（不是岔口，或有别的东西顶住）
#define RB_REASON_OUTER_LOST        (2)     // 卡在 WAIT：外侧连续掉下去，判成假警报
#define RB_REASON_HUMP_TIMEOUT      (3)     // 卡在 HUMP：内侧隆起后一直不落回（可能是急弯，不是岔口）
#define RB_REASON_TICK_MAX          (4)     // 某一段触到全局安全阀（多半是时长参数填错了）
#define RB_REASON_DETECT_TIMEOUT    (5)     // 识别耗时超过 RB_DETECT_MAX_TICKS，主动放弃
                                            // （这是挡十字路口的那一道，看到 5 就说明是它拦下来的）

//------------------------------------------------------------------------------------------------------------------
// 对外的状态量（main.c 的屏幕要显示，所以不能关在 .c 里当 static）
//------------------------------------------------------------------------------------------------------------------
extern roundabout_state_enum rb_state;  // 当前阶段，屏幕上 RB 后面那位
extern uint8  rb_reason;                // 上一次放弃的原因（RB_REASON_xxx），屏幕上 X 后面那位
extern uint8  rb_dbg_ch;                // 上一次识别里"涨得最猛"的是哪一路（1~3，0 = 没有）
extern uint16 rb_dbg_dur;               // 上一次识别从"候选"到"决定打角"一共花了多少拍（10ms/拍）
extern int16  rb_dbg_rise;              // 那一路涨了多少（峰值 - 起点），判"够不够驼峰"就看它
extern int16  rb_dbg_peak;              // 那一路的峰值（0~100）
extern uint16 rb_tick;                  // 当前阶段已经走了多少个 10ms 周期，屏幕最右边那 4 位数
extern int16  rb_total;                 // 四路归一化之和 0~400（目前没上屏，留着备用）

//------------------------------------------------------------------------------------------------------------------
// 接口
//------------------------------------------------------------------------------------------------------------------
void  roundabout_init(void);                    // 上电初始化一次，把状态机拉回干净状态
void  roundabout_process(void);                  // 每 10ms 调一次（放在 get_data() 最后）
uint8 roundabout_servo_takeover(float *angle);   // 需要接管舵机时返回 1，并把目标角度写进 *angle
float roundabout_speed_cap(void);                // 需要限速时返回限速值（脉冲/周期），0 = 不限
uint8 roundabout_forbid_right(void);             // 识别阶段返回 1：舵机不许往右打（见 .c 里的说明）

#endif
